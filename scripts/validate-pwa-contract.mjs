import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), 'utf8')
const parse = (relativePath) => JSON.parse(read(relativePath))
const failures = []
let checks = 0

function check(condition, message) {
  checks += 1
  if (!condition) failures.push(message)
  else console.log(`✓ ${message}`)
}

const index = read('index.html')
const manifest = parse('public/manifest.webmanifest')
const serviceWorker = read('public/sw.js')
const offline = read('public/offline.html')
const resetPage = read('public/reset-site.html')
const release = parse('public/release-status.json')
const main = read('src/main.tsx')
const workflow = read('.github/workflows/deploy-frontend.yml')
const canonicalSecurity = read('public/.well-known/security.txt')
const fallbackSecurity = read('public/security.txt')
const installHandler = serviceWorker.match(/self\.addEventListener\('install',[\s\S]*?\n\}\)/)?.[0] ?? ''

check(manifest.start_url === '/', 'Manifest start_url uses the custom-domain root')
check(manifest.scope === '/', 'Manifest scope uses the custom-domain root')
check(manifest.display === 'standalone', 'Manifest requests standalone display mode')
check(typeof manifest.name === 'string' && manifest.name.includes('ArivuKids'), 'Manifest has the ArivuKids product name')
check(typeof manifest.short_name === 'string' && manifest.short_name.length > 0, 'Manifest has a short name')
check(typeof manifest.theme_color === 'string' && manifest.theme_color.startsWith('#'), 'Manifest has a theme colour')
check(typeof manifest.background_color === 'string' && manifest.background_color.startsWith('#'), 'Manifest has a background colour')
check(Array.isArray(manifest.icons) && manifest.icons.length >= 1, 'Manifest declares at least one icon')
check(manifest.icons.every((icon) => icon.src.startsWith('/')), 'Manifest icon paths are root-relative')
check(index.includes('rel="manifest" href="/manifest.webmanifest"'), 'Application shell links the root manifest')
check(index.includes('rel="icon" href="/icons/kirthiverse-icon.svg"'), 'Application shell links the root application icon')
check(index.includes('name="theme-color"'), 'Application shell publishes a theme colour')
check(index.includes('name="referrer" content="strict-origin-when-cross-origin"'), 'Application shell sets a restrictive referrer policy')
check(index.includes('name="format-detection" content="telephone=no"'), 'Application shell disables accidental telephone detection')
check(index.includes('name="kvs-release-shell" content="KVS-PLATFORM-001"'), 'Application shell exposes its release identity')
check(index.includes('href="/reset-site.html"'), 'Application shell exposes browser recovery')
check(!index.includes('/kirthiverse/'), 'Application shell contains no unsupported repository-subpath deployment URLs')
check(serviceWorker.includes("const CACHE_NAME = 'kirthiverse-shell-v4-runtime-20260729'"), 'Service worker uses the runtime-recovery cache generation')
check(serviceWorker.includes("const RELEASE_MARKER = 'name=\"kvs-release-shell\" content=\"KVS-PLATFORM-001\"'"), 'Service worker validates the exact application shell')
check(serviceWorker.includes("const COMPILED_ASSET_PREFIX = '/assets/'"), 'Service worker restricts compiled assets to the root assets directory')
check(serviceWorker.includes("if (request.method !== 'GET') return"), 'Service worker never caches non-GET requests')
check(serviceWorker.includes('url.origin !== self.location.origin'), 'Service worker ignores cross-origin requests')
check(serviceWorker.includes("url.pathname.startsWith('/api/')"), 'Service worker excludes API traffic from caching')
check(serviceWorker.includes("request.mode === 'navigate'"), 'Service worker has explicit navigation handling')
check(serviceWorker.includes("fetch(request, { cache: 'no-store' })"), 'Service worker bypasses stale HTTP cache for navigation')
check(serviceWorker.includes('requiresCurrentApplicationShell'), 'Service worker distinguishes app-shell routes')
check(serviceWorker.includes('isCurrentApplicationShell'), 'Service worker validates network application shells')
check(serviceWorker.includes('stale or incomplete KirthiVerse application shell'), 'Service worker rejects stale or incomplete app HTML')
check(serviceWorker.includes("cache.match('/index.html')"), 'Service worker can recover SPA routes from the cached application shell')
check(serviceWorker.includes("cache.match('/offline.html')"), 'Service worker retains a dedicated offline fallback')
check(serviceWorker.includes("'/reset-site.html'"), 'Browser-repair page is precached')
check(installHandler.includes('event.waitUntil(precacheShell())'), 'Service worker install waits for complete precaching')
check(!installHandler.includes('skipWaiting'), 'Service worker install does not force immediate activation')
check(serviceWorker.includes("event.data?.type === 'SKIP_WAITING'"), 'Service worker supports controlled update activation')
check(serviceWorker.includes('self.clients.claim()'), 'Activated service worker claims open clients')
check(serviceWorker.includes('notifyAllClients'), 'Activated worker notifies open clients')
check(serviceWorker.includes("keys.filter((key) => key.startsWith('kirthiverse-')"), 'Activation removes obsolete KirthiVerse caches only')
check(serviceWorker.includes('await writeConnectivityState(cache, true)'), 'Offline navigation records recovery state')
check(serviceWorker.includes('KVS_OFFLINE_RECOVERY'), 'Service worker notifies the application about offline recovery')
check(serviceWorker.includes('KVS_CONNECTION_AVAILABLE'), 'Service worker notifies the application when connectivity returns')
check(serviceWorker.includes("Cache-Control', 'no-store'"), 'Injected offline documents are marked no-store')
check(serviceWorker.includes('role="status" aria-live="polite"'), 'Offline document banner is announced accessibly')
check(serviceWorker.includes("'/child-privacy.html'"), 'Child-readable privacy guidance is precached')
check(serviceWorker.includes("'/parent-guide.html'"), 'Parent guidance is precached')
check(serviceWorker.includes("'/security.html'"), 'Security guidance is precached')
check(serviceWorker.includes("'/security.txt'"), 'Visible security contact fallback is precached')
check(serviceWorker.includes("'/.well-known/security.txt'"), 'Canonical security contact is precached')
check(serviceWorker.includes("'/release-status.json'"), 'Release status is precached')
check(resetPage.includes('registration.unregister()'), 'Browser recovery unregisters stale workers')
check(resetPage.includes("cacheName.indexOf('kirthiverse-') === 0"), 'Browser recovery deletes only KirthiVerse caches')
check(!resetPage.includes('localStorage.clear'), 'Browser recovery preserves learner progress')
check(canonicalSecurity.includes('Canonical: https://arivukids.omsaravanabhava.org/.well-known/security.txt'), 'Canonical security contact declares its ArivuKids URL')
check(fallbackSecurity === canonicalSecurity, 'Root security contact fallback matches the canonical security contact')
check(workflow.includes('Package GitHub Pages artifact with hidden trust resources'), 'Workflow contains the manual Pages packaging stage')
check(workflow.includes('tar --dereference --hard-dereference'), 'Pages artifact is packaged as a tar archive')
check(workflow.includes("grep -Fx './.well-known/security.txt'"), 'Pages tar is inspected for the canonical security contact')
check(workflow.includes("grep -Fx './.nojekyll'"), 'Pages tar is inspected for .nojekyll')
check(workflow.includes('name: github-pages') && workflow.includes('path: ${{ runner.temp }}/artifact.tar'), 'Workflow uploads the expected github-pages artifact')
check(workflow.includes('compression-level: 0'), 'Pages tar is uploaded without a redundant compression pass')
check(!workflow.includes('uses: actions/upload-pages-artifact@v4'), 'Workflow does not use the hidden-file-excluding composite action')
check(offline.includes('kvs-offline-recovery'), 'Dedicated offline page identifies the recovery state')
check(offline.includes('role="status"') || offline.includes('role="main"'), 'Dedicated offline page contains an accessible status or main landmark')
check(main.includes("navigator.serviceWorker.register('/sw.js'"), 'Application registers the service worker from the custom-domain root')
check(main.includes("updateViaCache: 'none'"), 'Application bypasses cached service-worker scripts')
check(main.includes('registration.update()'), 'Application checks for worker updates')
check(main.includes("navigator.serviceWorker.addEventListener('controllerchange'"), 'Application reloads after controlled worker takeover')
check(!main.includes('/kirthiverse/sw.js'), 'Application does not register an unsupported repository-subpath service worker')
check(release.localFirst === true, 'Release contract remains local-first')
check(release.cloudChildProfiles === false, 'Release contract keeps cloud child profiles disabled')
check(release.schoolRosters === false, 'Release contract keeps school rosters disabled')
check(release.automatedOfflineRecovery === true, 'Release status records automated offline recovery')
for (const gate of ['pwa-root-deployment-contract', 'service-worker-cache-safety', 'hidden-trust-resource-deployment', 'root-security-contact-fallback', 'runtime-shell-identity', 'stale-service-worker-recovery', 'cache-bypass-navigation', 'browser-repair-flow']) {
  check(Array.isArray(release.qualityGates) && release.qualityGates.includes(gate), `Release status publishes ${gate}`)
}
check(workflow.includes('pnpm run validate:pwa'), 'GitHub Actions executes the PWA deployment-contract gate')
check(workflow.includes('pwa-contract.log'), 'GitHub Actions retains PWA contract diagnostics')

if (failures.length) {
  console.error('\nPWA deployment-contract validation failed:')
  failures.forEach((failure) => console.error(`✗ ${failure}`))
  process.exit(1)
}

console.log(`\n✓ PWA deployment-contract gate passed (${checks} controls)`)
